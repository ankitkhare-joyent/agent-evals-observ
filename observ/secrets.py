"""OpenBao client helpers: how a workload gets its secrets at runtime instead of from env files.

OpenBao is API-compatible with HashiCorp Vault, so the standard Python Vault client (hvac) works unchanged.

Two identities exist in this project:
  * the human operator: `userpass` login as `admin` (production: OIDC through your IdP + MFA)
  * workloads: AppRole, one role per workload, each bound to one narrow policy
    (production on Kubernetes: the `kubernetes` auth method, where the pod's service-account token *is*
    the identity, so there is no secret_id to distribute at all; on EC2/EKS: the `aws` auth method)
"""
from __future__ import annotations

import os
import threading
import time
from dataclasses import dataclass
from pathlib import Path

import hvac

ROOT = Path(__file__).resolve().parent.parent
BAO_DIR = ROOT / ".bao"
BAO_ADDR = os.environ.get("EVALS_BAO_ADDR", "http://127.0.0.1:38200")
KV_MOUNT = "secret"


def admin_client() -> hvac.Client:
    """Human/operator login. Reads the first admin password generated by scripts/bootstrap.sh."""
    client = hvac.Client(url=BAO_ADDR, timeout=10)
    password = (BAO_DIR / "bootstrap" / "admin-password").read_text().strip()
    client.auth.userpass.login(username="admin", password=password)
    return client


def approle_client(role: str) -> hvac.Client:
    """Workload login with AppRole: role_id (like a username, not secret) + secret_id (the credential)."""
    creds = BAO_DIR / "approle" / role
    client = hvac.Client(url=BAO_ADDR, timeout=10)
    client.auth.approle.login(role_id=(creds / "role_id").read_text().strip(),
                              secret_id=(creds / "secret_id").read_text().strip())
    return client


def read_kv(client: hvac.Client, path: str) -> dict:
    """Read the latest version of a KV v2 secret. Raises hvac.exceptions.Forbidden if the policy says no."""
    return client.secrets.kv.v2.read_secret_version(path=path, mount_point=KV_MOUNT,
                                                    raise_on_deleted_version=True)["data"]["data"]


class TokenKeeper:
    """Keeps a workload's OpenBao token alive for long runs (an eval suite can outlive a 30-minute token).

    Renews at ~2/3 of the TTL; if renewal is no longer possible (max TTL reached) it logs in again.
    This is what OpenBao Agent does for the sidecars; in-process code has to do it itself.
    """

    def __init__(self, role: str):
        self.role = role
        self.client = approle_client(role)
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._loop, name=f"bao-renew-{role}", daemon=True)
        self._thread.start()

    def _loop(self) -> None:
        while not self._stop.is_set():
            ttl = self.client.auth.token.lookup_self()["data"]["ttl"]
            if self._stop.wait(max(10, ttl * 2 // 3)):
                return
            try:
                self.client.auth.token.renew_self()
            except hvac.exceptions.VaultError:
                self.client = approle_client(self.role)   # past max TTL: fresh login

    def stop(self) -> None:
        self._stop.set()


@dataclass(frozen=True)
class RuntimeSecrets:
    anthropic_api_key: str
    langfuse_public_key: str
    langfuse_secret_key: str

    def __repr__(self) -> str:  # never let a secret end up in a log line or a traceback
        return "RuntimeSecrets(<redacted>)"


def load_eval_runner_secrets(export_env: bool = True) -> RuntimeSecrets:
    """What the eval runner needs, read with the eval-runner AppRole: the model key and a Langfuse API key.

    export_env=True puts the values into this process's environment (never onto disk), because the agent
    under test and the Anthropic/Langfuse SDKs read their credentials from there. The agent's own login to
    the inventory API is *not* here: the agent fetches that itself from the lakehouse project's OpenBao,
    exactly as it does in production. Each system owns its secrets.
    """
    client = approle_client("eval-runner")
    anthropic = read_kv(client, "evals/anthropic")
    lf = read_kv(client, "langfuse/api")
    s = RuntimeSecrets(anthropic["api_key"], lf["public_key"], lf["secret_key"])
    if export_env:
        os.environ.update({
            "ANTHROPIC_API_KEY": s.anthropic_api_key,
            "LANGFUSE_PUBLIC_KEY": s.langfuse_public_key,
            "LANGFUSE_SECRET_KEY": s.langfuse_secret_key,
        })
    client.auth.token.revoke_self()   # we have what we need; don't leave a live token behind
    return s


def wait_until_ready(timeout_s: float = 60) -> None:
    deadline = time.time() + timeout_s
    client = hvac.Client(url=BAO_ADDR, timeout=5)
    while True:
        try:
            health = client.sys.read_health_status(method="GET")
            if health["initialized"] and not health["sealed"]:
                return
        except Exception:  # noqa: BLE001, S110 - not up yet; keep polling until the deadline
            pass
        if time.time() > deadline:
            raise TimeoutError(f"OpenBao at {BAO_ADDR} is not healthy after {timeout_s}s")
        time.sleep(1)
